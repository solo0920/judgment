#!/usr/bin/env python3
"""Build the standalone, directly openable frontend artifact.

The FastAPI console serves the ES-module sources directly. This script bundles
those same sources into an IIFE for two other deployment paths:

* opening ``frontend/index.html`` with a ``file://`` URL
* uploading ``frontend/`` to Cloudflare Pages (or another static host)
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC_DIR = ROOT / "src" / "judgment" / "web" / "static"
DEFAULT_OUT_DIR = ROOT / "frontend"

MODULE_SCRIPT = '<script type="module" src="./assets/js/app.js"></script>'
BUNDLE_SCRIPTS = (
    '<script src="./config.js"></script>\n'
    '    <script src="./assets/js/app.js"></script>'
)


def _esbuild_command(explicit: str | None) -> list[str]:
    if explicit:
        return [explicit]
    direct = shutil.which("esbuild")
    if direct:
        return [direct]
    npx = shutil.which("npx")
    if npx:
        return [npx, "--yes", "esbuild"]
    raise SystemExit(
        "找不到 esbuild。請安裝 Node.js/esbuild，或以 --esbuild PATH 指定執行檔。"
    )


def _normalize_api_base(value: str) -> str:
    base = value.strip().rstrip("/")
    if not base:
        return ""
    if not re.match(r"^https?://", base, re.IGNORECASE):
        raise SystemExit("--api-base 必須以 http:// 或 https:// 開頭。")
    return base


def _is_within(path: Path, parent: Path) -> bool:
    return path == parent or parent in path.parents


def _guard_output_dir(out_dir: Path) -> None:
    protected = [
        STATIC_DIR,
        ROOT / "src",
        ROOT / "tests",
        ROOT / "scripts",
        ROOT / "specs",
        ROOT / "documents",
        ROOT / "data",
        ROOT / ".git",
        ROOT / ".venv",
    ]
    if out_dir in {ROOT, ROOT.parent} or any(
        _is_within(out_dir, path) for path in protected
    ):
        raise SystemExit(f"拒絕清除不安全的輸出目錄：{out_dir}")


def build(
    *,
    out_dir: Path,
    api_base: str = "",
    minify: bool = True,
    esbuild: str | None = None,
    keep_existing: bool = False,
) -> dict[str, object]:
    out_dir = out_dir.expanduser().resolve()
    _guard_output_dir(out_dir)

    required = [
        STATIC_DIR / "index.html",
        STATIC_DIR / "assets" / "styles.css",
        STATIC_DIR / "assets" / "themes.css",
        STATIC_DIR / "assets" / "js" / "app.js",
        STATIC_DIR / "favicon.svg",
    ]
    missing = [str(path.relative_to(ROOT)) for path in required if not path.is_file()]
    if missing:
        raise SystemExit(f"缺少前端來源檔案：{', '.join(missing)}")

    if out_dir.exists():
        if keep_existing:
            print(f"保留既有輸出目錄內容：{out_dir}")
        else:
            shutil.rmtree(out_dir)

    assets_dir = out_dir / "assets"
    (assets_dir / "js").mkdir(parents=True, exist_ok=True)

    shutil.copy2(STATIC_DIR / "assets" / "styles.css", assets_dir / "styles.css")
    shutil.copy2(STATIC_DIR / "assets" / "themes.css", assets_dir / "themes.css")
    shutil.copy2(STATIC_DIR / "favicon.svg", out_dir / "favicon.svg")

    command = [
        *_esbuild_command(esbuild),
        str(STATIC_DIR / "assets" / "js" / "app.js"),
        "--bundle",
        "--format=iife",
        "--target=es2020",
        "--outfile=" + str(assets_dir / "js" / "app.js"),
        "--log-level=warning",
    ]
    if minify:
        command.append("--minify")
    subprocess.run(command, check=True, cwd=ROOT)

    source_html = (STATIC_DIR / "index.html").read_text(encoding="utf-8")
    if MODULE_SCRIPT not in source_html:
        raise SystemExit(
            "index.html 找不到預期的 module script 標籤，無法產生 standalone frontend。"
        )
    built_html = source_html.replace(MODULE_SCRIPT, BUNDLE_SCRIPTS, 1)
    (out_dir / "index.html").write_text(built_html, encoding="utf-8")

    built_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    config = (
        "/* Generated by scripts/build_frontend.py — do not edit by hand. */\n"
        "window.JUDGMENT_CONFIG = Object.freeze({\n"
        f"  apiBase: {json.dumps(_normalize_api_base(api_base))},\n"
        f"  builtAt: {json.dumps(built_at)},\n"
        "});\n"
    )
    (out_dir / "config.js").write_text(config, encoding="utf-8")

    (out_dir / "_headers").write_text(
        "/*\n"
        "  X-Content-Type-Options: nosniff\n"
        "  Referrer-Policy: strict-origin-when-cross-origin\n"
        "  X-Frame-Options: DENY\n"
        "  Permissions-Policy: geolocation=(), microphone=(), camera=()\n"
        "\n"
        "/config.js\n"
        "  Cache-Control: no-cache\n"
        "\n"
        "/index.html\n"
        "  Cache-Control: no-cache\n",
        encoding="utf-8",
    )

    bundle = assets_dir / "js" / "app.js"
    return {
        "out_dir": str(out_dir),
        "index": str(out_dir / "index.html"),
        "bundle": str(bundle),
        "bundle_bytes": bundle.stat().st_size,
        "api_base": _normalize_api_base(api_base),
        "minified": minify,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="產生可直接以 file:// 開啟並可部署到 Cloudflare Pages 的 frontend/"
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help=f"輸出目錄（預設：{DEFAULT_OUT_DIR.relative_to(ROOT)}）",
    )
    parser.add_argument(
        "--api-base",
        default="",
        help="寫入 config.js 的預設後端位址；留空則使用同源／file:// 預設值",
    )
    parser.add_argument(
        "--esbuild",
        default=None,
        help="esbuild 執行檔路徑；未指定時使用 PATH 或 npx",
    )
    parser.add_argument(
        "--no-minify",
        action="store_true",
        help="保留未壓縮的 bundle（除錯用）",
    )
    parser.add_argument(
        "--keep-existing",
        action="store_true",
        help="不先清空輸出目錄（僅更新本次產生的檔案）",
    )
    args = parser.parse_args(argv)

    summary = build(
        out_dir=args.out_dir,
        api_base=args.api_base,
        minify=not args.no_minify,
        esbuild=args.esbuild,
        keep_existing=args.keep_existing,
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
